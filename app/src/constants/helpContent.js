/**
 * Получить раздел справки по его ID.
 * При отсутствии совпадения возвращает первый раздел (decks).
 */
export function getHelpSection(topicId) {
  if (!topicId) return HELP_SECTIONS[0];
  const normalized = topicId === 'editor' ? 'creator' : (topicId === 'study_back' ? 'study' : topicId);
  return HELP_SECTIONS.find(s => s.id === normalized) || HELP_SECTIONS[0];
}
