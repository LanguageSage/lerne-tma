const {chromium} = require('playwright');
(async () => {
  const browser = await chromium.launch({headless: true});
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/*', route => {
    const host = new URL(route.request().url()).hostname;
    if (['127.0.0.1','cdn.tailwindcss.com','unpkg.com','fonts.googleapis.com','fonts.gstatic.com'].includes(host)) return route.continue();
    return route.abort();
  });
  await page.goto('http://127.0.0.1:8050/');
  await page.waitForFunction(()=>typeof usersData !== 'undefined' && usersData.length===50);
  await page.locator('#users-grid-pager button').last().click();
  await page.waitForFunction(()=>usersData.length===11);
  await page.evaluate(()=>switchTab('decks'));
  await page.waitForFunction(()=>currentRenderedDecks.length===50);
  await page.click('#btn-deck-next');
  await page.waitForFunction(()=>currentRenderedDecks.length===11);
  await page.fill('#deck-search','Колода 1');
  await page.evaluate(()=>filterDecks());
  await page.waitForFunction(()=>deckTotal===11);
  await page.evaluate(()=>switchTab('folders'));
  await page.waitForFunction(()=>foldersData.length===50);
  await page.locator('#folders-list-pager button').last().click();
  await page.waitForFunction(()=>foldersData.length===11);
  await page.fill('#folder-search','Папка 61');
  await page.evaluate(()=>renderFoldersList());
  await page.waitForFunction(()=>foldersData.length===1 && foldersData[0].id===61);
  await page.evaluate(()=>openDeckPreviewModal(1,'Колода 1'));
  await page.waitForFunction(()=>previewCardsList.length===50);
  await page.locator('#preview-cards-table-pager button').last().click();
  await page.waitForFunction(()=>previewCardsList.length===15);
  await page.evaluate(()=>openCardEditModal(65));
  await page.waitForFunction(()=>!document.getElementById('modal-edit-card').classList.contains('hidden'));
  const context = await page.inputValue('#edit-card-context');
  if(context.length<=240) throw Error('Editor received truncated detail');
  await page.fill('#edit-card-front','Browser edited');
  await page.evaluate(()=>saveCardEdit());
  await page.waitForFunction(()=>document.getElementById('modal-edit-card').classList.contains('hidden'));
  await page.fill('#preview-cards-search','Browser edited');
  await page.evaluate(()=>filterPreviewCards());
  await page.waitForFunction(()=>previewCardsList.length===1 && previewCardsList[0].front==='Browser edited');
  await page.screenshot({path:'.test-tmp/admin-egress-desktop.png',fullPage:true});
  await page.setViewportSize({width:430,height:932});
  await page.screenshot({path:'.test-tmp/admin-egress-mobile.png',fullPage:true});
  console.log(JSON.stringify({passed:['users pages','deck pages','deck search','folder pages','folder search','card pages','full detail edit','saved search'],contextLength:context.length,errors}));
  await browser.close();
  if(errors.length) process.exitCode=1;
})().catch(error=>{console.error(error);process.exit(1)});
