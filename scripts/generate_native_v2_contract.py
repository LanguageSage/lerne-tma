"""Generate the browser's Native V2 JSON Schema from the pure card-core models."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pydantic.json_schema import GenerateJsonSchema
from pydantic_core import to_jsonable_python

from api.card_core.lerne_card_core.structured_cards_v2 import ContentV2, EditableTextData, FreeTextData, V2Model

TARGET = ROOT / 'app/src/utils/nativeV2Schema.generated.js'


class SchemaWithDefaults(GenerateJsonSchema):
    def default_schema(self, schema):
        result = super().default_schema(schema)
        if schema.get('default_factory_takes_data'):
            raise ValueError('Native V2 defaults cannot depend on other fields')
        if 'default_factory' in schema:
            result['default'] = to_jsonable_python(schema['default_factory']())
        return result


def check_pydantic_hooks(node):
    if isinstance(node, dict):
        if str(node.get('type', '')).startswith('function-'):
            function = node['function']['function']
            # JSON already has the envelope literal and policy object. These
            # adapters only distinguish Python int/float and model instances.
            if function not in (ContentV2.strict_version, EditableTextData.revalidate_policy,
                                FreeTextData.revalidate_policy, V2Model.native_v2_semantics):
                raise ValueError(f'Native V2 hook has no client representation: {function}')
        for child in node.values():
            check_pydantic_hooks(child)
    elif isinstance(node, (list, tuple)):
        for child in node:
            check_pydantic_hooks(child)


def check_schema_vocabulary(node, definitions):
    supported = {'$defs', '$ref', 'additionalProperties', 'anyOf', 'const', 'default', 'discriminator',
                 'description', 'enum', 'items', 'maximum', 'maxItems', 'maxLength', 'minimum',
                 'minItems', 'minLength', 'oneOf', 'pattern', 'properties', 'required', 'title', 'type', 'x-rules'}
    if node.keys() - supported:
        raise ValueError(f'Unsupported Native V2 schema keywords: {node.keys() - supported}')
    if 'oneOf' in node and 'discriminator' not in node:
        raise ValueError('Native V2 oneOf requires a discriminator')
    if 'anyOf' in node:
        types = [(definitions[branch['$ref'].rsplit('/', 1)[1]] if '$ref' in branch else branch).get('type')
                 for branch in node['anyOf']]
        if None in types or len(set(types)) != len(types) or {'number', 'integer'} <= set(types):
            raise ValueError('Native V2 anyOf must have disjoint JSON types')
    nested = [node[key] for key in ('items', 'additionalProperties') if isinstance(node.get(key), dict)]
    nested += [child for key in ('properties', '$defs') for child in node.get(key, {}).values()]
    nested += node.get('anyOf', []) + node.get('oneOf', [])
    for child in nested:
        check_schema_vocabulary(child, definitions)


def schema_source():
    check_pydantic_hooks(ContentV2.__pydantic_core_schema__)
    schema = ContentV2.model_json_schema(schema_generator=SchemaWithDefaults)
    check_schema_vocabulary(schema, schema['$defs'])
    return ('// Generated by scripts/generate_native_v2_contract.py. Do not edit.\n'
            'export default ' + json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=True) + ';\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = schema_source()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != expected:
            raise SystemExit(f'{TARGET.name} is stale. Run python scripts/generate_native_v2_contract.py')
    else:
        TARGET.write_text(expected, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
