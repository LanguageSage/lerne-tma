"""Generate and verify the canonical SQLite schema manifest and Android JS module."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "sqlite_schema/lerne_sqlite_schema"
MIGRATIONS_DIR = PACKAGE / "migrations"
MANIFEST_PATH = PACKAGE / "schema_manifest.json"
JS_TARGET = ROOT / "app/src/sqlite/schema.generated.js"
SCHEMA_FORMAT = "lerne-sqlite-v1"


def collect_migrations() -> tuple[dict, list[dict]]:
    sql_files = sorted(MIGRATIONS_DIR.glob("*.sql"))
    if not sql_files:
        raise RuntimeError(f"No SQL migrations found in {MIGRATIONS_DIR}")

    manifest_entries: list[dict] = []
    js_entries: list[dict] = []
    expected_version = 1

    for path in sql_files:
        raw = path.read_bytes()
        if b"\r" in raw:
            raise RuntimeError(f"{path.name} must use LF line endings")
        stem = path.stem
        prefix = stem.split("_", 1)[0]
        if not prefix.isdigit() or int(prefix) != expected_version:
            raise RuntimeError(
                f"Expected sequential migration prefix {expected_version:04d}_*.sql, got {path.name}"
            )
        digest = hashlib.sha256(raw).hexdigest()
        manifest_entries.append({
            "version": expected_version,
            "name": stem,
            "filename": path.name,
            "sha256": digest,
        })
        js_entries.append({
            "version": expected_version,
            "name": stem,
            "filename": path.name,
            "sha256": digest,
            "sql": raw.decode("utf-8"),
        })
        expected_version += 1

    manifest = {
        "format": SCHEMA_FORMAT,
        "schema_version": len(manifest_entries),
        "migrations": manifest_entries,
    }
    return manifest, js_entries


def render_js(manifest: dict, js_entries: list[dict]) -> str:
    payload = {
        "format": manifest["format"],
        "schema_version": manifest["schema_version"],
        "migrations": js_entries,
    }
    encoded = json.dumps(payload, indent=2, ensure_ascii=True)
    return (
        "// Generated by scripts/generate_sqlite_schema.py from sqlite_schema/. Do not edit.\n"
        f"export const SQLITE_SCHEMA_MANIFEST = {encoded};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify manifest and JS module match SQL files")
    args = parser.parse_args()

    manifest, js_entries = collect_migrations()
    expected_manifest = json.dumps(manifest, indent=2, ensure_ascii=True) + "\n"
    expected_js = render_js(manifest, js_entries)

    if args.check:
        if not MANIFEST_PATH.exists() or MANIFEST_PATH.read_text(encoding="utf-8") != expected_manifest:
            raise SystemExit(f"{MANIFEST_PATH.name} is stale. Run python scripts/generate_sqlite_schema.py")
        if not JS_TARGET.exists() or JS_TARGET.read_text(encoding="utf-8") != expected_js:
            raise SystemExit(f"{JS_TARGET.name} is stale. Run python scripts/generate_sqlite_schema.py")
        print(f"PASS: SQLite schema manifest & JS target match ({manifest['schema_version']} migration(s))")
        return

    MANIFEST_PATH.write_text(expected_manifest, encoding="utf-8", newline="\n")
    JS_TARGET.parent.mkdir(parents=True, exist_ok=True)
    JS_TARGET.write_text(expected_js, encoding="utf-8", newline="\n")
    print(f"Generated {MANIFEST_PATH} and {JS_TARGET} (schema_version={manifest['schema_version']})")


if __name__ == "__main__":
    main()
